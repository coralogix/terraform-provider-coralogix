#!/usr/bin/env bash
set -euo pipefail

checker=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/check-generated-resources.sh
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
repo=$work/repo
mkdir -p "$repo/tools/iac-codegen/internal/version" "$repo/internal/provider/generated/thing" "$repo/examples"
git -C "$repo" init -q
git -C "$repo" config user.email test@example.com
git -C "$repo" config user.name Test
git -C "$repo" config commit.gpgsign false

cat >"$work/tfgen" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
mkdir -p "$5"
body='current body'
if [[ -f "$5/behavior-overrides.yaml" ]]; then
  body=$(awk -F': ' '/^generated_body: / { print $2; exit }' "$5/behavior-overrides.yaml")
fi
printf '// Code generated by coralogix-iac-codegen. DO NOT EDIT.\n%s\n' "$body" >"$5/resource.go"
EOF
chmod +x "$work/tfgen"
export TFGEN=$work/tfgen

write_version() {
  printf 'package version\nconst Current = "v0.1.0-beta.%s"\n' "$1" >"$repo/tools/iac-codegen/internal/version/version.go"
}
write_versions() {
  printf '# Code generated by coralogix-iac-codegen. DO NOT EDIT.\nthing: v0.1.0-beta.%s\n' "$1" >"$repo/internal/provider/generated/versions.yaml"
}
write_resource() {
  printf '// Code generated by coralogix-iac-codegen. DO NOT EDIT.\n%s\n' "$1" >"$repo/internal/provider/generated/thing/resource.go"
}
commit_all() {
  git -C "$repo" add .
  git -C "$repo" commit -qm "$1"
}
expect_failure() {
  local message=$1
  if (cd "$repo" && bash "$checker") >"$work/result" 2>&1; then
    printf 'Expected failure: %s\n' "$message" >&2
    exit 1
  fi
  if ! grep -qF "$message" "$work/result"; then
    cat "$work/result" >&2
    exit 1
  fi
}
expect_success() {
  if ! (cd "$repo" && bash "$checker") >"$work/result" 2>&1; then
    cat "$work/result" >&2
    exit 1
  fi
}

printf '//go:generate make -C ../.. codegen RESOURCE=Thing OUT=thing\n' >"$repo/internal/provider/codegen.go"
printf 'example\n' >"$repo/examples/example.txt"
write_version 1
write_versions 1
write_resource 'current body'
commit_all base
expect_success

write_version 2
write_resource 'old body'
commit_all version
expect_failure 'does not use generator v0.1.0-beta.2'

write_versions 2
commit_all 'current manifest'
expect_failure 'Generated files are stale'

write_resource 'current body'
commit_all regenerated
expect_success

# A manifest-only update must also prove that the generated body is current.
write_versions 1
write_resource 'old body'
commit_all 'old package baseline'
write_versions 2
commit_all 'manifest only'
expect_failure 'Generated files are stale'
write_resource 'current body'
commit_all 'manifest and body'
expect_success

# An input-only change can require new output with no version change.
printf 'generated_body: updated\n' >"$repo/internal/provider/generated/thing/behavior-overrides.yaml"
commit_all 'override only'
expect_failure 'Generated files are stale'
write_resource updated
commit_all 'override and body'
expect_success

mkdir -p "$repo/internal/provider/generated/other"
printf 'another resource\n' >"$repo/internal/provider/generated/other/resource.go"
commit_all unlisted
expect_failure 'Generated resource other is missing from internal/provider/codegen.go'
