package generator

import (
	"bytes"
	"errors"
	"fmt"
	"go/token"
	"maps"
	"os"
	"path/filepath"
	"slices"

	"github.com/coralogix/terraform-provider-coralogix/tools/iac-codegen/internal/version"
	"go.yaml.in/yaml/v4"
)

// versionsFileName is the file next to the generated packages that holds the generator version of
// each package. The generated Go files do not hold the version, so a new version changes only
// this file and the files whose output changes.
const versionsFileName = "versions.yaml"

// versionsHeaderLine is the first line of versions.yaml. A versions.yaml without it stops the run.
const versionsHeaderLine = "# Code generated by coralogix-iac-codegen. DO NOT EDIT."

const versionsHeader = versionsHeaderLine + "\n# The generator version of each generated package.\n"

// renderVersions returns versions.yaml next to output. The line of the output package gets
// version.Current. The line of a package whose directory is gone goes. The other lines stay.
func renderVersions(output string) (providerFile, error) {
	parent := filepath.Dir(output)
	path := filepath.Join(parent, versionsFileName)
	versions, err := readVersions(path)
	if err != nil {
		return providerFile{}, err
	}
	for name := range versions {
		if info, err := os.Stat(filepath.Join(parent, name)); err != nil || !info.IsDir() {
			delete(versions, name)
		}
	}
	versions[filepath.Base(output)] = version.Current
	var buf bytes.Buffer
	buf.WriteString(versionsHeader)
	for _, name := range slices.Sorted(maps.Keys(versions)) {
		fmt.Fprintf(&buf, "%s: %s\n", name, versions[name])
	}
	return providerFile{path, buf.Bytes()}, nil
}

// readVersions reads versions.yaml. A missing file has no lines. A file without the generator
// header is not the generator's, so the run stops.
func readVersions(path string) (map[string]string, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("inspect %s: %w", versionsFileName, err)
	}
	if line, _, _ := bytes.Cut(data, []byte("\n")); string(line) != versionsHeaderLine {
		return nil, fmt.Errorf("%s is not generator-owned: it lacks a valid generator header", path)
	}
	var versions map[string]string
	if err := yaml.Unmarshal(data, &versions); err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	if versions == nil {
		versions = map[string]string{}
	}
	for name := range versions {
		if !token.IsIdentifier(name) {
			return nil, fmt.Errorf("%s: %q is not a package name", path, name)
		}
	}
	return versions, nil
}
